// worked is a transcript of a session that edited a file and ran a command —
// the shape that has something to record.
func worked() *transcript.Session {
	return &transcript.Session{
		Harness: "cursor",
		ID:      "sess-1",
		Path:    "/tmp/sess-1.json",
		Project: "shop",
		Turns: []transcript.Turn{
			{Role: "user", Text: "fix the checkout crash when cart is empty"},
			{Role: "tool", Tool: "edit_file", Input: "internal/cart/checkout.go"},
			{Role: "tool", Tool: "run_terminal_cmd", Input: "go test ./internal/cart", Status: "ok"},
		},
	}
}

// A host with no Stop hook never tells Logos the session ended, so the activity
// log the Claude Code path builds from is empty. The host's own transcript is
// not: it has the prompt, the files and the commands. Without this, every
// session in Cursor, Codex or any other hookless host that forgot to checkpoint
// was lost outright.
func TestASessionThatEndedWithoutACheckpointIsRecordedFromTheHostsOwnTranscript(t *testing.T) {
	vault := t.TempDir()

	c, _, err := AutoCheckpoint(vault, worked(), "shop")
	if err != nil {
		t.Fatal(err)
	}
	if c == nil {
		t.Fatal("a session that edited a file and ran a command recorded nothing")
	}
	if !c.Auto {
		t.Errorf("the checkpoint is not marked auto, so it reads as an agent's own")
	}
	if c.Task != "fix the checkout crash when cart is empty" {
		t.Errorf("task = %q, want the session's first prompt", c.Task)
	}
	if len(c.Files) == 0 || len(c.Commands) == 0 {
		t.Errorf("files = %v, commands = %v — the work was not carried over", c.Files, c.Commands)
	}
	// Where it came from has to be readable off the file itself: an unverified
	// record whose provenance is invisible is one nobody can weigh.
	if !strings.Contains(c.State, "cursor") || !strings.Contains(c.State, "sess-1") {
		t.Errorf("state = %q, want it to name the harness and the transcript", c.State)
	}
	// Guessing these is worse than leaving them empty — the next agent reads
	// failed as a paid-for ruling and will not re-try what it names.
	if len(c.Verified) != 0 || len(c.Failed) != 0 || c.Next != "" {
		t.Errorf("an unreviewed record claimed verified/failed/next: %+v", c)
	}
}

// A session that only read and asked has nothing worth a checkpoint, and one
// written anyway turns every quick question into a handoff.
func TestATranscriptWithNoWorkWritesNoAutoCheckpoint(t *testing.T) {
	vault := t.TempDir()

	s := worked()
	s.Turns = []transcript.Turn{
		{Role: "user", Text: "what does this package do?"},
		{Role: "assistant", Text: "it parses transcripts"},
	}

	c, _, err := AutoCheckpoint(vault, s, "shop")
	if err != nil {
		t.Fatal(err)
	}
	if c != nil {
		t.Errorf("a session that changed nothing was checkpointed: %+v", c)
	}
}

// Two Logos servers in two windows of the same host both see the same newest
// transcript when they close, and both would harvest it. The second one has to
// find the first one's record and leave it alone.
func TestTheSameTranscriptIsNotRecordedTwice(t *testing.T) {
	vault := t.TempDir()

	first, _, err := AutoCheckpoint(vault, worked(), "shop")
	if err != nil || first == nil {
		t.Fatalf("first = %v, err = %v", first, err)
	}
	second, _, err := AutoCheckpoint(vault, worked(), "shop")
	if err != nil {
		t.Fatal(err)
	}
	if second != nil {
		t.Errorf("the same transcript was recorded a second time: %s", second.Slug)
	}
}

// An agent's own checkpoint outranks this one always: the auto record exists
// because nobody wrote one, so finding one means there is nothing to do.
func TestAnAgentsOwnCheckpointIsNotFollowedByAnAutoOne(t *testing.T) {
	vault := t.TempDir()

	if _, err := session.WriteAuto(vault, session.Checkpoint{
		Project: "shop", Agent: "agent", Task: "real work",
	}); err != nil {
		t.Fatal(err)
	}
	// Written as auto above only because that is the cheap way to get a
	// checkpoint on disk here; what matters is that it does not name this
	// transcript, so it is somebody else's record and must not be extended.
	c, _, err := AutoCheckpoint(vault, worked(), "shop")
	if err != nil {
		t.Fatal(err)
	}
	if c == nil {
		t.Fatal("an unrelated earlier checkpoint stopped this session being recorded")
	}
}

// The task line is the one line of an auto record that says what the session
// was for, and on real records it was a host's wrapper: Claude Code's
// <local-command-caveat>, a bare /logos:context-connect, a pasted block, "hi".
// Every host wraps some of what it records as the user's turn; the first turn
// that asks for something is the request.
func TestAnAutoRecordsTaskIsTheFirstRequestNotTheHostsWrapperAroundIt(t *testing.T) {
	s := worked()
	s.Turns = append([]transcript.Turn{
		{Role: "user", Text: "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.</local-command-caveat>"},
		{Role: "user", Text: "<command-name>/logos:context-connect</command-name>\n<command-message>logos:context-connect</command-message>\n<command-args></command-args>"},
		{Role: "user", Text: "<local-command-stdout>Set model to opus</local-command-stdout>"},
		{Role: "user", Text: "<environment_context>\n  <cwd>/src/shop</cwd>\n</environment_context>"},
		{Role: "user", Text: "<user_instructions>\nAlways run the tests.\n</user_instructions>"},
		{Role: "user", Text: "This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion."},
		{Role: "user", Text: `<pasted_content id="89a9">a stack trace nobody typed</pasted_content>`},
		{Role: "user", Text: "hi"},
		{Role: "user", Text: "Thanks!"},
	}, s.Turns...)

	c, _, err := AutoCheckpoint(t.TempDir(), s, "shop")
	if err != nil || c == nil {
		t.Fatalf("no record: %v", err)
	}
	if c.Task != "fix the checkout crash when cart is empty" {
		t.Errorf("task = %q, want the first turn that asks for something", c.Task)
	}
}

// A slash command's arguments are the person's own words, and the command is
// how they asked; the user's text around a paste is theirs too.
func TestASlashCommandsArgumentsAndTheWordsAroundAPasteAreTheRequest(t *testing.T) {
	for in, want := range map[string]string{
		"<command-name>/code-review</command-name>\n<command-message>code-review</command-message>\n<command-args>main..fix-login</command-args>": "/code-review main..fix-login",
		`<pasted_content id="1">panic: nil map</pasted_content> why does checkout panic here`:                                                     "why does checkout panic here",
		"/review the cart package": "/review the cart package",
	} {
		s := worked()
		s.Turns[0].Text = in
		c, _, err := AutoCheckpoint(t.TempDir(), s, "shop")
		if err != nil || c == nil {
			t.Fatalf("no record: %v", err)
		}
		if c.Task != want {
			t.Errorf("task from %q = %q, want %q", in, c.Task, want)
		}
	}
}

// A session in which nobody asked for anything has no task, and an empty line
// says so better than a wrapper standing in for one.
func TestASessionWithNoRequestHasNoTask(t *testing.T) {
	s := worked()
	s.Turns[0].Text = "<local-command-caveat>Caveat: generated by the user while running local commands.</local-command-caveat>"
	c, _, err := AutoCheckpoint(t.TempDir(), s, "shop")
	if err != nil || c == nil {
		t.Fatalf("no record: %v", err)
	}
	if c.Task != "" {
		t.Errorf("task = %q, want none", c.Task)
	}
}

// The hook path folds a prompt onto one line and kept "Hi! Can you fix…";
// the transcript path read "Hi!" alone and threw the whole turn away. One
// session got two different tasks depending on which path recorded it.
func TestAGreetingOnItsOwnLineDoesNotHideTheRequestAfterIt(t *testing.T) {
	if got, ok := Request("Hi!\n\nCan you fix the checkout crash?"); !ok || got != "Can you fix the checkout crash?" {
		t.Errorf("Request = %q, %v, want the line after the greeting", got, ok)
	}
	if _, ok := Request("thanks\nok"); ok {
		t.Error("a turn of only acknowledgements asks for nothing")
	}
}

// PersonWrote kept every line left once host text was out, so a bare /compact
// typed on a host that sends it as plain text, or a turn that was only a kept-
// out <private> span, counted as the person's words — and a distiller's guess
// about what was hidden behind "[private]" passed as something they said.
func TestABareSlashCommandOrAKeptOutSpanIsNotThePersonsWords(t *testing.T) {
	for _, p := range []string{"/compact", "  /model  ", "[private]", "[private] [private]"} {
		if PersonWrote(p) {
			t.Errorf("PersonWrote(%q) = true", p)
		}
	}
	for _, p := range []string{"no", "[private] keep v1", "/compact then fix the cart"} {
		if !PersonWrote(p) {
			t.Errorf("PersonWrote(%q) = false", p)
		}
	}
}

// A first prompt that was only a kept-out span became the auto checkpoint's
// task as "[private]", and the next agent was told the person asked for that.
func TestAFirstPromptThatWasOnlyAKeptOutSpanIsNotTheRequest(t *testing.T) {
	for _, p := range []string{"[private]", "[private] [private]", "  [private]\n"} {
		if got, ok := Request(p); ok {
			t.Errorf("Request(%q) = %q, want no request", p, got)
		}
	}
	if got, ok := Request("[private]\nfix the cart total"); !ok || got != "fix the cart total" {
		t.Errorf("Request = %q, %v, want the line after the kept-out span", got, ok)
	}
	if got, _ := Request("[private] keep v1 pricing"); got != "[private] keep v1 pricing" {
		t.Errorf("a line with words beside the marker is still a request, got %q", got)
	}
}
